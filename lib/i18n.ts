/** RELATION_ORDER relations that never take a count qualifier (× N) in copy. */
export const SINGLE_ONLY_RELATIONS: Relation[] = ["husband", "wife", "father", "mother"];

export function buildConfirmationMessage(
  draft: Record<Relation, number>,
  lang: Lang,
  relationOrder: Relation[],
): string {
  const lines: string[] = [];
  lines.push(CONFIRM_INTRO[lang], "");
  for (const r of relationOrder) {
    const count = draft[r] || 0;
    if (count === 0) continue;
    const label = RELATION_LABELS[r][lang];
    if (SINGLE_ONLY_RELATIONS.includes(r)) lines.push(`- ${label}`);
    else lines.push(`- ${label} × ${count}`);
  }
  lines.push("", CONFIRM_OUTRO[lang]);
  return lines.join("\n");
}

